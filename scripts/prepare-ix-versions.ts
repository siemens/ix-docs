const __dirname = path.resolve();
const __docs = path.join(__dirname, 'docs');
const __autogenerated = path.join(__docs, 'autogenerated');
const __autogeneratedApi = path.join(__autogenerated, 'api');

export const IX_VERSIONS_FILE = path.join(__autogenerated, 'ix-versions.json');

const owner = 'siemens';
const repo = 'ix';

function encodeRef(ref: string) {
  return ref.split('/').map(encodeURIComponent).join('/');
}

async function fetchGitHub(
  url: string,
  accept = 'application/vnd.github+json'
) {
  const token = process.env.GITHUB_TOKEN;
  const headers: Record<string, string> = { Accept: accept };

  if (token) {
    const response = await fetch(url, {
      headers: { ...headers, Authorization: `Bearer ${token}` },
    });
    // Tokens can be rejected (e.g. org policies), public data is readable without.
    // raw.githubusercontent.com answers rejected tokens with 404.
    const rejected =
      [401, 403].includes(response.status) ||
      (response.status === 404 &&
        new URL(url).host === 'raw.githubusercontent.com');
    if (!rejected) {
      return response;
    }
  }

  return fetch(url, { headers });
}

/**
 * Commit of a branch or ref (e.g. `refs/pull/123/head`), all files are read from the same commit
 */
async function resolveCommit(ref: string) {
  const response = await fetchGitHub(
    `https://api.github.com/repos/${owner}/${repo}/commits/${encodeRef(ref)}`,
    'application/vnd.github.sha'
  );
  if (!response.ok) {
    throw new Error(`Failed to resolve "${ref}" (${response.status})`);
  }
  return (await response.text()).trim();
}

async function fetchRaw(commit: string, file: string) {
  const response = await fetchGitHub(
    `https://raw.githubusercontent.com/${owner}/${repo}/${commit}/${file}`
  );
  if (response.status === 404) {
    return undefined;
  }
  if (!response.ok) {
    throw new Error(`Failed to fetch ${file} (${response.status})`);
  }
  return response.text();
}

async function fetchChangesets(commit: string): Promise<Changeset[]> {
  const response = await fetchGitHub(
    `https://api.github.com/repos/${owner}/${repo}/contents/.changeset?ref=${commit}`
  );
  if (!response.ok) {
    throw new Error(`Failed to list changesets (${response.status})`);
  }

  const files = (await response.json()) as { name: string; type: string }[];
  const changesets = await Promise.all(
    files
      .filter(
        ({ name, type }) =>
          type === 'file' && name.endsWith('.md') && name !== 'README.md'
      )
      .map(async ({ name }) => {
        const content = await fetchRaw(commit, `.changeset/${name}`);
        return content ? parseChangeset(name, content) : null;
      })
  );

  return changesets.filter((changeset): changeset is Changeset => !!changeset);
}

async function readComponents() {
  const components: Record<string, ComponentApi & { since?: string }> = {};

  if (!(await fs.pathExists(__autogeneratedApi))) {
    return components;
  }

  for (const tag of await fs.readdir(__autogeneratedApi)) {
    const apiFile = path.join(__autogeneratedApi, tag, 'api.mdx');
    const tagsFile = path.join(__autogeneratedApi, tag, 'tags.mdx');
    if (!(await fs.pathExists(apiFile))) {
      continue;
    }

    components[tag] = {
      ...parseApiMdx(await fs.readFile(apiFile, 'utf8')),
      since: (await fs.pathExists(tagsFile))
        ? parseComponentSince(await fs.readFile(tagsFile, 'utf8'))
        : undefined,
    };
  }

  return components;
}

/**
 * Doc directories (e.g. `components/card`) and the component tags documented on their code tab.
 */
async function readPageComponents() {
  const pages: Record<string, string[]> = {};
  const files = await glob('**/*.mdx', {
    cwd: __docs,
    ignore: ['autogenerated/**'],
  });

  for (const file of files) {
    const content = await fs.readFile(path.join(__docs, file), 'utf8');
    const tags = Array.from(
      content.matchAll(/autogenerated\/api\/([a-z0-9-]+)\/api\.mdx/g),
      ([, tag]) => tag
    );
    if (tags.length === 0) {
      continue;
    }

    const dir = path.dirname(file).split(path.sep).join('/');
    pages[dir] = [...new Set([...(pages[dir] ?? []), ...tags])];
  }

  return pages;
}

/**
 * Since tags without a valid version are hidden, point out the missing data in the IX repository
 */
function warnInvalidSince(
  components: Record<string, ComponentApi & { since?: string }>
) {
  const invalid = Object.entries(components).flatMap(([tag, component]) =>
    [
      { name: '', since: component.since },
      ...component.props,
      ...component.events,
    ]
      .filter(({ since }) => since !== undefined && !parseVersion(since))
      .map(({ name, since }) => `${name ? `${tag}.${name}` : tag} ("${since}")`)
  );

  if (invalid.length > 0) {
    console.warn(
      `Hiding ${invalid.length} since tags without a valid version: ${invalid.join(', ')}`
    );
  }
}

type ResolvedVersion = Pick<IxVersionInfo, 'version' | 'source'>;

async function resolveFromChangesets(
  branch: string
): Promise<ResolvedVersion | null> {
  try {
    const commit = await resolveCommit(branch);
    const pkg = await fetchRaw(commit, 'packages/core/package.json');
    if (!pkg) {
      throw new Error(`packages/core/package.json not found on ${branch}`);
    }

    const changesets = await fetchChangesets(commit);
    const currentVersion = JSON.parse(pkg).version as string;
    const version = getUpcomingVersion(currentVersion, changesets);

    console.log(
      `IX ${currentVersion} on "${branch}" (${commit.slice(0, 7)}) with ${changesets.length} pending changesets -> ${version}`
    );

    return { version, source: 'changesets' };
  } catch (e) {
    console.warn(
      `Could not resolve IX version from changesets on "${branch}", using fallback.`,
      e instanceof Error ? e.message : e
    );
    return null;
  }
}

/**
 * `breaking-change` front matter of the doc pages (`<dir>/index.md(x)`), keyed by doc directory.
 * Invalid front matter fails the build.
 */
async function readBreakingChanges() {
  const result: Record<string, BreakingChange> = {};
  const files = await glob('**/index.{md,mdx}', {
    cwd: __docs,
    ignore: ['autogenerated/**'],
  });

  for (const file of files) {
    const { data } = matter(await fs.readFile(path.join(__docs, file), 'utf8'));
    try {
      const breakingChange = parseBreakingChangeFrontMatter(
        data[BREAKING_CHANGE_FRONT_MATTER_KEY]
      );
      if (breakingChange) {
        result[path.dirname(file).split(path.sep).join('/')] = breakingChange;
      }
    } catch (e) {
      throw new Error(
        `Invalid front matter in docs/${file}: ${e instanceof Error ? e.message : e}`
      );
    }
  }

  return result;
}

/**
 * Members of a breaking change front matter by component tag of the page,
 * names that are not part of the page's API tables are reported
 */
function resolveBreakingChangeMembers(
  dir: string,
  breakingChange: BreakingChange,
  tag: string | undefined,
  pageTags: string[],
  components: Record<string, ComponentApi>
) {
  const members =
    breakingChange.properties.length + breakingChange.events.length;
  if (members === 0) {
    return {};
  }
  if (!tag) {
    console.warn(
      `docs/${dir}: "${BREAKING_CHANGE_FRONT_MATTER_KEY}" lists properties or events, but the page has no API tables`
    );
    return {};
  }

  const grouped = groupBreakingChangeMembers(tag, breakingChange);
  const unknown: string[] = [];

  for (const [memberTag, { props, events }] of Object.entries(grouped)) {
    const api = pageTags.includes(memberTag)
      ? components[memberTag]
      : undefined;
    const prefix = memberTag === tag ? '' : `${memberTag}.`;
    const check = (
      names: string[],
      known: ComponentApi['props'],
      kind: string
    ) =>
      names
        .filter((name) => !known.some((member) => member.name === name))
        .forEach((name) => unknown.push(`${kind} ${prefix}${name}`));

    if (!api) {
      unknown.push(
        ...[...props, ...events].map((name) => `${memberTag}.${name}`)
      );
      delete grouped[memberTag];
      continue;
    }
    check(props, api.props, 'property');
    check(events, api.events, 'event');
  }

  if (unknown.length > 0) {
    console.warn(
      `docs/${dir}: "${BREAKING_CHANGE_FRONT_MATTER_KEY}" members not found in the API tables of the page: ${unknown.join(', ')}`
    );
  }

  return grouped;
}

/**
 * @param ref IX branch or ref of the downloaded artifact, `IX_CHANGESETS_BRANCH` takes precedence
 */
export default async function prepareIxVersions(ref = 'main') {
  const branch = process.env.IX_CHANGESETS_BRANCH || ref;
  const components = await readComponents();
  warnInvalidSince(components);
  const pageComponents = await readPageComponents();
  const breakingChanges = await readBreakingChanges();

  const resolved: ResolvedVersion =
    (await resolveFromChangesets(branch)) ?? getFallbackVersion(__dirname);
  const currentMajor = parseVersion(resolved.version)!.major;

  const info: IxVersionInfo = {
    ...resolved,
    branch: resolved.source === 'changesets' ? branch : undefined,
    currentMajor,
    pages: {},
  };

  // Breaking change tags of the API tables by component tag
  const apiBreakingChanges: Record<
    string,
    { version: string; href: string; members: BreakingChangeMembers }
  > = {};

  const dirs = new Set([
    ...Object.keys(pageComponents),
    ...Object.keys(breakingChanges),
  ]);
  for (const dir of dirs) {
    const tags = pageComponents[dir] ?? [];
    const folder = dir.split('/').pop();
    const tag = tags.find((t) => t === `ix-${folder}`) ?? tags[0];

    const breakingChange = breakingChanges[dir];
    const active =
      breakingChange &&
      isActiveBreakingChange(breakingChange.version, currentMajor);
    const breaking = active
      ? {
          version: breakingChange.version,
          href: getMigrationGuideUrl(breakingChange.version),
          description: breakingChange.description,
        }
      : undefined;

    info.pages[dir] = {
      tag,
      since: tag ? components[tag]?.since : undefined,
      breaking,
    };

    if (!breaking) {
      continue;
    }

    if (
      !info.breakingChanges ||
      isNewerVersion(breaking.version, info.breakingChanges.version)
    ) {
      info.breakingChanges = {
        version: breaking.version,
        docUrl: breaking.href,
      };
    }

    const members = resolveBreakingChangeMembers(
      dir,
      breakingChange,
      tag,
      tags,
      components
    );
    for (const [memberTag, { props, events }] of Object.entries(members)) {
      const existing = apiBreakingChanges[memberTag];
      apiBreakingChanges[memberTag] = {
        version: breaking.version,
        href: breaking.href,
        members: {
          props: [...new Set([...(existing?.members.props ?? []), ...props])],
          events: [
            ...new Set([...(existing?.members.events ?? []), ...events]),
          ],
        },
      };
    }
  }

  // Replace tags of previous runs, e.g. if the artifact was not downloaded again.
  // Only `api.mdx` is imported by the docs, `props.mdx` and `events.mdx` stay untouched.
  for (const tag of Object.keys(components)) {
    const apiFile = path.join(__autogeneratedApi, tag, 'api.mdx');
    const content = await fs.readFile(apiFile, 'utf8');
    const breaking = apiBreakingChanges[tag];
    const updated = breaking
      ? injectBreakingChangeTags(
          content,
          breaking.version,
          breaking.href,
          breaking.members
        )
      : removeBreakingChangeTags(content);

    if (updated !== content) {
      await fs.writeFile(apiFile, updated);
    }
  }

  await fs.ensureDir(__autogenerated);
  await fs.writeJSON(IX_VERSIONS_FILE, info, { spaces: 2 });

  const breakingPages = Object.values(info.pages).filter(
    (page) => page.breaking
  ).length;
  console.log(
    `IX version info: ${info.version} (${info.source}), showing since tags >= ${currentMajor - 1}.0.0, ${breakingPages} pages with breaking changes`
  );
}

function isNewerVersion(a: string, b: string) {
  const [x, y] = [parseVersion(a)!, parseVersion(b)!];
  return (x.major - y.major || x.minor - y.minor || x.patch - y.patch) > 0;
}
