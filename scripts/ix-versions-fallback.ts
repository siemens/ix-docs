import fs from 'fs';
import path from 'path';
import {
  IX_CORE_PACKAGE,
  IxVersionInfo,
  parseDependencyVersion,
  parseVersion,
} from '../src/lib/ix-versions';

function readJson(file: string) {
  return fs.existsSync(file)
    ? JSON.parse(fs.readFileSync(file, 'utf8'))
    : undefined;
}

/**
 * Version of the downloaded artifact, or of `@siemens/ix` in `package.json`
 */
export function getFallbackVersion(
  rootDir: string
): Pick<IxVersionInfo, 'version' | 'source'> {
  const artifactVersion = readJson(
    path.join(rootDir, 'docs/autogenerated/version.json')
  )?.version;
  if (parseVersion(artifactVersion)) {
    return { version: artifactVersion, source: 'artifact' };
  }

  const pkg = readJson(path.join(rootDir, 'package.json'));
  const version = parseDependencyVersion(pkg?.dependencies?.[IX_CORE_PACKAGE]);
  if (!version) {
    throw new Error(
      `Could not resolve the IX version from ${IX_CORE_PACKAGE} in package.json`
    );
  }
  return { version, source: 'package' };
}

/**
 * Version info without since or breaking change data of single pages
 */
export function getFallbackVersionInfo(rootDir: string): IxVersionInfo {
  const resolved = getFallbackVersion(rootDir);
  return {
    ...resolved,
    currentMajor: parseVersion(resolved.version)!.major,
    pages: {},
  };
}
