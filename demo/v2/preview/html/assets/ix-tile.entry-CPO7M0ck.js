const Tile = class {
  constructor(hostRef) {
    registerInstance(this, hostRef);
  }
  get hostElement() {
    return getElement(this);
  }
  /**
   * Size of the tile - one of 'small', 'medium' or 'large'
   */
  size = "medium";
  hasHeaderSlot = false;
  hasFooterSlot = false;
  handleHeaderSlotChange() {
    this.hasHeaderSlot = !!this.hostElement.querySelector('[slot="header"]');
  }
  handleFooterSlotChange() {
    this.hasFooterSlot = !!this.hostElement.querySelector('[slot="footer"]');
  }
  render() {
    return h(Host, { key: "f7b8617c4c5ef2b2942538cf71fdee564be1ab43", class: {
      "tile-small": this.size === "small",
      "tile-medium": this.size === "medium",
      "tile-big": this.size === "big"
    } }, h("div", { key: "814e5729e7a1f91f9c33214302a71388f982f261", class: {
      "tile-header": true,
      "has-content": this.hasHeaderSlot
    } }, h("slot", { key: "404841da4a2029338fe20b18d724a72934737eee", name: "header", onSlotchange: () => this.handleHeaderSlotChange() })), h("div", { key: "33006e1926a94fef9cf7408d4b70193d03693199", class: "tile-subheader" }, h("slot", { key: "100a134bfd8ecfd9e3dda7abc4e2e3cb3aaf2c7c", name: "subheader" })), h("div", { key: "b24b6277b691f04ac40bb8eb7ab5f753753448e9", class: "tile-content" }, h("slot", { key: "485efce30225a49260f87c3b1b39a43702ab2c15" })), h("div", { key: "27ae95305f3c4adf43844d887058d7649a39550e", class: {
      "tile-footer": true,
      "has-content": this.hasFooterSlot
    } }, h("slot", { key: "761c900463234b5079e4b9c4797f83e9aeb946f7", name: "footer", onSlotchange: () => this.handleFooterSlotChange() })));
  }
};
Tile.style = tileCss();
export {
  Tile as ix_tile
};
